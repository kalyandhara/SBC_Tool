"""Weekly transit report generator.

Combines the transit-wise historical studies with current transits and
price data into a weekly markdown report:
  1. Gold / Silver / Nifty snapshot, trend and reversal zones
  2. Current Jupiter / Mars / Mercury nakshatra transits with
     historical performance stats
  3. Mars-Jupiter same-sign status
  4. Moon's daily nakshatra schedule for the coming week
  5. Volatility and positive market windows
  6. Risk-management rules for the week

Study aggregate CSVs in data/output are reused; missing ones are
regenerated by invoking the study scripts.  Output:
data/output/weekly_report_<date>.md (also printed to stdout).
"""

import argparse
import csv
import datetime
import glob
import os
import subprocess
import sys

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, _ROOT)
sys.path.insert(0, os.path.join(_ROOT, "scripts"))

from study_moon_nakshatra import moon_nakshatra_at_open  # noqa: E402

from sbc.market_data import get_ohlc  # noqa: E402
from sbc.planets import positioned_planets  # noqa: E402
from sbc.transits import same_sign_periods  # noqa: E402

OUT_DIR = os.path.join(_ROOT, "data", "output")
ASSETS = ["gold", "silver", "nifty"]
PLANETS = ["Jupiter", "Mars", "Mercury"]
STUDY_START = "2002-01-01"

POS_UP_PCT = 55.0
CAUTION_UP_PCT = 47.0
POS_TRANSIT_MOVE = 2.0
POS_TRANSIT_PCT = 60.0
CAUTION_TRANSIT_MOVE = -1.0
CAUTION_TRANSIT_PCT = 40.0
VOL_QUARTILE = 0.75


def ensure_studies():
    """Regenerate missing study CSVs by invoking the study scripts."""
    existing = {os.path.basename(p)
                for p in glob.glob(os.path.join(OUT_DIR, "*.csv"))}

    def have(prefix):
        return any(f.startswith(prefix) for f in existing)

    jobs = []
    for asset in ASSETS:
        if not have(f"study_{asset}_moon_nakshatra_daily"):
            jobs.append(["scripts/study_moon_nakshatra.py", "--asset", asset])
    for planet in PLANETS:
        for asset in ASSETS:
            if have(f"study_{asset}_{planet.lower()}_nakshatra"):
                continue
            start = "2007-01-01" if asset == "nifty" else STUDY_START
            jobs.append(["scripts/study_nakshatra.py", "--planet", planet,
                         "--asset", asset, "--start", start])
    for asset in ASSETS:
        if have(f"study_{asset}_MarsJupiter_same_sign"):
            continue
        start = "2007-01-01" if asset == "nifty" else STUDY_START
        jobs.append(["scripts/study_same_sign.py", "--asset", asset,
                     "--start", start])

    for job in jobs:
        print(f"[weekly_report] generating missing study: {' '.join(job)}")
        subprocess.run([sys.executable] + job, cwd=_ROOT, check=True)


def load_nakshatra_agg(prefix):
    """Load per-nakshatra aggregates for a planet study.

    Returns {nakshatra: {visits, pos, neg, avg_move, pos_pct}} or None
    when the study CSV is missing.
    """
    matches = glob.glob(os.path.join(OUT_DIR, prefix + "*.csv"))
    if not matches:
        return None
    with open(matches[0], encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    agg = {}
    for r in rows:
        a = agg.setdefault(r["nakshatra"],
                           {"visits": 0, "pos": 0, "neg": 0, "moves": []})
        a["visits"] += 1
        a["moves"].append(float(r["move_pct"]))
        if r["result"] == "Positive":
            a["pos"] += 1
        elif r["result"] == "Negative":
            a["neg"] += 1
    for a in agg.values():
        a["avg_move"] = round(sum(a["moves"]) / len(a["moves"]), 2)
        a["pos_pct"] = round(a["pos"] / a["visits"] * 100.0, 1)
    return agg


def load_moon_agg(asset):
    """Load the Moon daily profile aggregates for an asset.

    Returns {nakshatra: {days, up_pct, avg_range, avg_gap, avg_move}}
    or None when missing.
    """
    matches = glob.glob(os.path.join(OUT_DIR,
                                     f"study_{asset}_moon_nakshatra_daily"
                                     "*_agg.csv"))
    if not matches:
        return None
    with open(matches[0], encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    out = {}
    for r in rows:
        out[r["nakshatra"]] = {
            "days": int(r["days"]),
            "up_pct": float(r["up_pct"]),
            "avg_range": float(r["avg_range"]),
            "avg_gap": float(r["avg_gap"]),
            "avg_move": float(r["avg_move"]),
        }
    return out


def vol_thresholds(moon_agg):
    """Top-quartile average-range threshold per asset's Moon profile."""
    if not moon_agg:
        return None
    ranges = sorted(a["avg_range"] for a in moon_agg.values())
    idx = min(int(len(ranges) * VOL_QUARTILE), len(ranges) - 1)
    return ranges[idx]


def outlook(asset, today, lookback_days=40):
    """Return snapshot dict: trend, changes, 30d high/low, swing zones."""
    rows = get_ohlc(asset, (today - datetime.timedelta(days=lookback_days))
                    .isoformat(), today.isoformat())
    if len(rows) < 10:
        return None
    closes = [r["close"] for r in rows]

    def chg(bars):
        return ((closes[-1] - closes[-1 - bars]) / closes[-1 - bars] * 100.0
                if len(closes) > bars else 0.0)

    up_5 = closes[-1] > closes[-6] if len(closes) > 5 else True
    up_20 = closes[-1] > closes[-21] if len(closes) > 20 else True
    trend = "Up" if up_5 and up_20 else ("Down" if not up_5 and not up_20
                                         else "Mixed/Sideways")

    swing_lookback = 2
    highs, lows = [], []
    for i in range(swing_lookback, len(rows) - swing_lookback):
        window = rows[i - swing_lookback:i + swing_lookback + 1]
        if rows[i]["high"] == max(w["high"] for w in window):
            highs.append(rows[i]["high"])
        if rows[i]["low"] == min(w["low"] for w in window):
            lows.append(rows[i]["low"])

    return {
        "close": closes[-1],
        "last_date": rows[-1]["time"],
        "chg_5": round(chg(5), 2),
        "chg_20": round(chg(20), 2),
        "trend": trend,
        "high_30": max(r["high"] for r in rows),
        "low_30": min(r["low"] for r in rows),
        "swing_highs": highs[-3:],
        "swing_lows": lows[-3:],
    }


def _hist_cell(stats, asset):
    st = stats.get(asset)
    return (f"{st['avg_move']:+.2f}% ({st['pos_pct']}%, "
            f"{st['visits']} visits)" if st else "n/a")


def transit_readings(current, today):
    """Return rows of current Jupiter/Mars/Mercury transits with stats."""
    planets, _ayanamsa, _sun, _moon, _tithi = positioned_planets(
        today.isoformat())
    by_name = {p["name"]: p for p in planets}
    rows = []
    for planet in PLANETS:
        p = by_name[planet]
        row = {
            "planet": planet,
            "sign": p["sign"],
            "nakshatra": p["nakshatra"],
            "pada": p["pada"],
            "retrograde": "R" if p["retrograde"] else "-",
            "stats": {},
        }
        for asset in ASSETS:
            agg = load_nakshatra_agg(
                f"study_{asset}_{planet.lower()}_nakshatra")
            if agg and p["nakshatra"] in agg:
                row["stats"][asset] = agg[p["nakshatra"]]
        rows.append(row)
    return rows


def moon_schedule(today, days=7):
    """Return [(date, nakshatra, pada)] for the coming days (IST open)."""
    out = []
    for offset in range(days):
        d = today + datetime.timedelta(days=offset)
        nak, pada = moon_nakshatra_at_open(d)
        out.append((d, nak, pada))
    return out


def same_sign_status(today):
    start = today - datetime.timedelta(days=500)
    end = today + datetime.timedelta(days=500)
    periods = same_sign_periods("Mars", "Jupiter", start, end)
    today_s = today.isoformat()
    current = [p for p in periods
               if p["start"] <= today_s <= p["end"]]
    upcoming = [p for p in periods if p["start"] > today_s]
    return current, upcoming


def render_md(readings, moon_days, current_ss, upcoming_ss, snapshots,
              today):
    moon_aggs = {a: load_moon_agg(a) for a in ASSETS}
    vol_thr = {a: vol_thresholds(moon_aggs[a]) for a in ASSETS}

    lines = [f"# Weekly Transit Report — {today}", ""]

    lines += ["## 1. Market snapshot, trend and reversal zones", ""]
    lines += ["| Asset | Close | 5d chg | 20d chg | Trend | "
              "30d High (res) | 30d Low (sup) |",
              "|---|---|---|---|---|---|---|"]
    for asset in ASSETS:
        s = snapshots[asset]
        if not s:
            continue
        lines.append(
            f"| {asset.capitalize()} | {s['close']:,.2f} | "
            f"{s['chg_5']:+.2f}% | {s['chg_20']:+.2f}% | {s['trend']} | "
            f"{s['high_30']:,.2f} | {s['low_30']:,.2f} |")
    lines += ["", "**Reversal zones (recent swings):**", ""]
    for asset in ASSETS:
        s = snapshots[asset]
        if not s:
            continue
        res = ", ".join(f"{v:,.2f}" for v in s["swing_highs"])
        sup = ", ".join(f"{v:,.2f}" for v in s["swing_lows"])
        lines.append(f"- **{asset.capitalize()}** — resistance: {res}; "
                     f"support: {sup}")
    lines.append("")

    lines += ["## 2. Current transits (Jupiter / Mars / Mercury)", ""]
    lines += ["| Planet | Sign | Nakshatra (pada) | Retro | "
              "Gold hist | Silver hist | Nifty hist |",
              "|---|---|---|---|---|---|---|"]
    for row in readings:
        lines.append(
            f"| {row['planet']} | {row['sign']} | "
            f"{row['nakshatra']} ({row['pada']}) | {row['retrograde']} | "
            f"{_hist_cell(row['stats'], 'gold')} | "
            f"{_hist_cell(row['stats'], 'silver')} | "
            f"{_hist_cell(row['stats'], 'nifty')} |")
    lines += ["", "**Window reading:**"]
    for row in readings:
        for asset in ASSETS:
            st = row["stats"].get(asset)
            if not st:
                continue
            if (st["avg_move"] >= POS_TRANSIT_MOVE
                    and st["pos_pct"] >= POS_TRANSIT_PCT):
                tag = "POSITIVE window"
            elif (st["avg_move"] <= CAUTION_TRANSIT_MOVE
                    or st["pos_pct"] <= CAUTION_TRANSIT_PCT):
                tag = "CAUTION window"
            else:
                tag = "neutral"
            lines.append(f"- {row['planet']} in {row['nakshatra']} → "
                         f"{asset.capitalize()}: {tag} "
                         f"({st['avg_move']:+.2f}% avg, {st['pos_pct']}% pos)")
    lines.append("")

    lines += ["## 3. Mars–Jupiter same-sign status", ""]
    if current_ss:
        for p in current_ss:
            lines.append(f"- **Live period: {p['start']} → {p['end']} "
                         f"({p['sign']}, {p['days']:.0f}d)** — metals "
                         f"historically positive (gold 74%, silver 63%), "
                         f"Nifty negative (31% pos, avg −1.65%)")
    else:
        lines.append("- No live Mars–Jupiter same-sign period.")
    for p in upcoming_ss[:2]:
        lines.append(f"- Next: {p['start']} → {p['end']} ({p['sign']})")
    lines.append("")

    lines += ["## 4. Moon's daily nakshatra schedule (next 7 days)", ""]
    lines += ["| Date | Nakshatra at open (9:15 IST) | Nifty up% | "
              "Nifty vol | Gold up% | Gold vol | Silver up% | Silver vol |",
              "|---|---|---|---|---|---|---|---|"]
    for d, nak, pada in moon_days:
        cells = [f"{d.isoformat()} ({d.strftime('%a')})", f"{nak} ({pada})"]
        for asset in ("nifty", "gold", "silver"):
            agg = moon_aggs[asset]
            if agg and nak in agg:
                a = agg[nak]
                thr = vol_thr[asset]
                vol = f"{a['avg_range']:.2f}%"
                if thr and a["avg_range"] >= thr:
                    vol += " HIGH"
                cells.append(f"{a['up_pct']:.1f}%")
                cells.append(vol)
            else:
                cells += ["n/a", "n/a"]
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")

    lines += ["## 5. Volatility and positive windows", ""]
    pos_windows = []
    high_vol_days = []
    caution_days = []
    for d, nak, _pada in moon_days:
        for asset in ASSETS:
            agg = moon_aggs[asset]
            if not agg or nak not in agg:
                continue
            a = agg[nak]
            if vol_thr[asset] and a["avg_range"] >= vol_thr[asset]:
                high_vol_days.append(f"{d.isoformat()} {nak} "
                                     f"({asset}: range {a['avg_range']:.2f}%)")
            if a["up_pct"] >= POS_UP_PCT:
                pos_windows.append(f"{d.isoformat()} {nak} "
                                   f"({asset}: {a['up_pct']:.1f}% up days)")
            elif a["up_pct"] <= CAUTION_UP_PCT:
                caution_days.append(f"{d.isoformat()} {nak} "
                                    f"({asset}: {a['up_pct']:.1f}% up days)")
    lines.append("**Positive day-bias windows (≥55% historical up rate):**")
    lines += [f"- {w}" for w in pos_windows] or ["- none this week"]
    lines += ["", "**High-volatility days (top-quartile range):**"]
    lines += [f"- {w}" for w in high_vol_days] or ["- none this week"]
    lines += ["", "**Caution day-bias windows (≤47% up rate):**"]
    lines += [f"- {w}" for w in caution_days] or ["- none this week"]
    lines.append("")

    lines += ["## 6. Risk-management rules for this week", ""]
    lines += [
        "- Risk 0.5-1% of capital per trade; halve size in CAUTION "
        "windows, avoid fresh longs in negative ones.",
        "- Metals long bias is valid only while the Mars–Jupiter "
        "same-sign period holds; Nifty longs stay reduced (31% "
        "historical positive in this regime).",
        "- Jyeshtha Moon days: avoid metals longs (gold 40.5%, silver "
        "38.9% up historically).",
        "- Widen intraday stops on HIGH-volatility days (range in top "
        "quartile).",
        "- Flat transit results (|move| < 0.1%) mark chop — reduce "
        "targets, skip breakout entries until the next ingress.",
        "- Full rulebook: docs/risk_rulebook.md",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Weekly transit report")
    parser.add_argument("--date", default=datetime.date.today().isoformat(),
                        help="report anchor date (YYYY-MM-DD)")
    parser.add_argument("--days", type=int, default=7,
                        help="days ahead for the Moon schedule")
    parser.add_argument("--no-csv", action="store_true",
                        help="do not save the markdown report")
    args = parser.parse_args()

    import contextlib

    with contextlib.suppress(Exception):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    today = datetime.date.fromisoformat(args.date)
    ensure_studies()

    readings = transit_readings(PLANETS, today)
    moon_days = moon_schedule(today, args.days)
    current_ss, upcoming_ss = same_sign_status(today)
    snapshots = {a: outlook(a, today) for a in ASSETS}

    md = render_md(readings, moon_days, current_ss, upcoming_ss,
                   snapshots, today)
    print(md)
    if not args.no_csv:
        os.makedirs(OUT_DIR, exist_ok=True)
        path = os.path.join(OUT_DIR, f"weekly_report_{today}.md")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(md)
        print(f"\nSaved: {path}")


if __name__ == "__main__":
    main()
