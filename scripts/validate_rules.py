"""Grade every astro rule against NIFTY history (sbc.rule_validation).

  python scripts/validate_rules.py                 # writes docs/research/rule_validation_<date>.md + .json
  python scripts/validate_rules.py --perm 200      # faster, coarser p-values

Needs data/market.db (scripts/refresh_market_data.py --full) and, for speed,
data/fingerprints.db (scripts/build_fingerprints.py).
"""

import argparse
import datetime as dt
import json
import math
import os
import sys
import time
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from sbc import rule_validation as rv  # noqa: E402

OUT_DIR = Path(__file__).resolve().parent.parent / "docs" / "research"


def _pct(x, digits=2):
    return "–" if x is None or (isinstance(x, float) and not math.isfinite(x)) else f"{x * 100:.{digits}f}%"


def _bps(x):
    return "–" if x is None or (isinstance(x, float) and not math.isfinite(x)) else f"{x * 1e4:+.1f}"


def _num(x, fmt="{:.3f}"):
    return "–" if x is None or (isinstance(x, float) and not math.isfinite(x)) else fmt.format(x)


def render(report: dict, title: str = "Astro rule validation",
           generator: str = "scripts/validate_rules.py", intro: list[str] | None = None) -> str:
    s = report["sample"]
    era_names = list(report["results"][0]["eras"]) if report["results"] else []
    lines = [
        f"# {title} — NIFTY ({report['generated'][:10]})",
        "",
        f"Sample: {s['first']} → {s['last']}, {s['sessions']} sessions. "
        f"Horizons: {', '.join(f'{h}d' for h in report['horizons'])}. "
        f"Permutations: {report['n_permutations']} (circular shift). "
        f"Fingerprint version `{report['fingerprint_version']}`.",
        "",
        f"Generated by `{generator}`; method in `sbc/stats.py` and `sbc/rule_validation.py`.",
        "",
        *[line for paragraph in (intro or []) for line in (paragraph, "")],
        "- **excess**: average return on signal days in the called direction, minus the market's own "
        "drift, in basis points per trade (directional rules), or the extra |move| on flagged days "
        "(event rules).",
        "- **hit / base**: share of calls that were right, against what the same calls would score "
        "with a constant guess.",
        "- **q**: p-value after Benjamini–Hochberg correction across every test in this report.",
        f"- **eras**: excess in {' / '.join(era_names)}.",
        "- **years**: years in which the rule came out ahead / years with signal days.",
        "",
    ]
    verdicts = {}
    for r in report["results"]:
        verdicts.setdefault(r["verdict"], []).append(f"{r['rule']} ({r['horizon']}d)")
    lines += ["## Summary", ""]
    for v in ("edge", "inconsistent", "no edge", "insufficient"):
        items = verdicts.get(v, [])
        lines.append(f"- **{v}** ({len(items)}): {', '.join(items) if items else '—'}")
    lines.append("")

    for kind, heading in (("directional", "Directional rules"), ("event", "Volatility (event) rules")):
        if not any(r["kind"] == kind for r in report["results"]):
            continue
        lines += [f"## {heading}", ""]
        if kind == "directional":
            lines += ["| rule | h | n (L/S) | excess bps | hit | base | p | q | eras bps | years | verdict |",
                      "|---|---|---|---|---|---|---|---|---|---|---|"]
        else:
            lines += ["| rule | h | n | abs on | abs off | ratio | p | q | eras bps | years | verdict |",
                      "|---|---|---|---|---|---|---|---|---|---|---|"]
        rows = sorted((r for r in report["results"] if r["kind"] == kind),
                      key=lambda r: (r["rule"], r["horizon"]))
        for r in rows:
            eras = " / ".join(_bps(v) for v in r["eras"].values())
            years = f"{r['years_right']}/{r['years']}"
            if r.get("status") != "ok":
                lines.append(f"| {r['rule']} | {r['horizon']} | {r['n']} | – | – | – | – | – | – | – | "
                             f"{r['verdict']} |")
            elif kind == "directional":
                lines.append(
                    f"| {r['rule']} | {r['horizon']} | {r['n']} ({r['n_long']}/{r['n_short']}) | "
                    f"{_bps(r['excess'])} | {_pct(r['hit_rate'], 1)} | {_pct(r['baseline'], 1)} | "
                    f"{_num(r['p'])} | {_num(r['q'])} | {eras} | {years} | **{r['verdict']}** |")
            else:
                lines.append(
                    f"| {r['rule']} | {r['horizon']} | {r['n']} | {_pct(r['abs_on'])} | "
                    f"{_pct(r['abs_off'])} | {_num(r['vol_ratio'], '{:.2f}')} | {_num(r['p'])} | "
                    f"{_num(r['q'])} | {eras} | {years} | **{r['verdict']}** |")
        lines.append("")

    lines += ["## Rule definitions", "", "| rule | kind | source | definition |", "|---|---|---|---|"]
    seen = set()
    for r in report["results"]:
        if r["rule"] in seen:
            continue
        seen.add(r["rule"])
        lines.append(f"| {r['rule']} | {r['kind']} | `{r['source']}` | {r['description']} |")
    lines.append("")
    return "\n".join(lines)


def write(report: dict, name: str, markdown: str) -> Path:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    stem = OUT_DIR / f"{name}_{dt.date.today().isoformat()}"
    stem.with_suffix(".json").write_text(json.dumps(report, indent=1), encoding="utf-8")
    stem.with_suffix(".md").write_text(markdown, encoding="utf-8")
    return stem


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--perm", type=int, default=1000, help="permutations per test")
    parser.add_argument("--start")
    parser.add_argument("--end")
    args = parser.parse_args()

    t0 = time.perf_counter()
    report = rv.run(n_perm=args.perm, start=args.start, end=args.end)
    intro = ["Each rule is tested as stated in its source module; nothing is fitted. "
             "2007–2020 is the cleaner out-of-sample era (ad-hoc backtests used 2021+ data)."]
    write(report, "rule_validation", render(report, intro=intro))
    print(f"wrote docs/research/rule_validation_*.md/.json in {time.perf_counter() - t0:.0f}s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
