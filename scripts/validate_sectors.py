"""Out-of-sample test of the sector vedha scenarios (sbc.sector_validation).

  python scripts/refresh_market_data.py --research --full   # first: download the series
  python scripts/validate_sectors.py                        # writes docs/research/sector_validation_<date>.md + .json
"""

import argparse
import os
import sys
import time
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from sbc import sector_validation as sv  # noqa: E402
from scripts.validate_rules import _bps, _num, _pct, write  # noqa: E402


def render(report: dict) -> str:
    res = report["results"]
    verdicts = Counter(r["verdict"] for r in res)
    replicated = sum(r["replicates"] for r in res)
    lines = [
        f"# Sector vedha scenarios, out of sample ({report['generated'][:10]})",
        "",
        "Generated by `scripts/validate_sectors.py`; method in `sbc/sector_validation.py`.",
        "",
        f"The scenarios in `sbc/sector_signals.py` were fitted on {report['fit_start']} onward. This "
        f"report grades every finding on the years **before** {report['fit_start']}, which the fit "
        "never saw, with the Phase 2 harness (excess over the target's own drift, circular-shift "
        f"p-value, {report['n_permutations']} permutations, BH across the out-of-sample tests).",
        "",
        f"- Out of sample: **{verdicts.get('edge', 0)} edge**, {verdicts.get('wrong way', 0)} wrong way, "
        f"{verdicts.get('no edge', 0)} no edge, {verdicts.get('insufficient', 0)} insufficient "
        f"(of {len(res)} findings).",
        f"- Replication check: {replicated} of {len(res)} findings show a positive excess in the fit window, "
        "as claimed. A finding that doesn't replicate there points at a difference between this test and "
        "the original backtest (signal days, return convention, unadjusted prices).",
        "",
        "## Price series", "",
        "| target | members | first | last | sessions |", "|---|---|---|---|---|",
    ]
    for t, info in report["targets"].items():
        lines.append(f"| {t} | {', '.join(info['members'])} | {info['first']} | {info['last']} | {info['sessions']} |")
    lines += [
        "", "## Findings", "",
        "Claimed = the scenario's own numbers (fit window). Excess = mean return in the claimed "
        "direction minus the drift, in bps. n = active trading days.", "",
        "| pair | sector | target | h | claimed avg / win / n | fit: n, excess, up share | "
        "out of sample: n, excess, hit vs base | p | q | verdict |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in sorted(res, key=lambda r: (r["sector"], r["pair"], r["target"], r["h"])):
        o, f = r["oos"], r["fit"]
        fit = (f"{f['n']}, {_bps(f.get('excess'))}, {_pct(f.get('up_share_on'), 0)}"
               if f.get("status") == "ok" else f"{f['n']}, –")
        oos = (f"{o['n']}, {_bps(o.get('excess'))}, {_pct(o.get('hit_rate'), 0)} vs {_pct(o.get('baseline'), 0)}"
               if o.get("status") == "ok" else f"{o['n']}, –")
        lines.append(
            f"| {r['pair']} | {r['sector']} | {r['target']} | {r['h']} | "
            f"{_pct(r['claimed_avg'])} / {_pct(r['claimed_win'], 0)} / {r['claimed_n']} | {fit} | {oos} | "
            f"{_num(o.get('p'))} | {_num(o.get('q'))} | **{r['verdict']}** |")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--perm", type=int, default=1000, help="permutations per test")
    args = parser.parse_args()
    t0 = time.perf_counter()
    report = sv.run(n_perm=args.perm)
    write(report, "sector_validation", render(report))
    print(f"wrote docs/research/sector_validation_*.md/.json in {time.perf_counter() - t0:.0f}s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
