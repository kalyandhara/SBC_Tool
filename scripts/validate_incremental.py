"""Do the astro signals add anything beyond market controls? (sbc.incremental)

  python scripts/validate_incremental.py            # writes docs/research/incremental_validation_<date>.md + .json
  python scripts/validate_incremental.py --perm 200
"""

import argparse
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from sbc import incremental as inc  # noqa: E402
from scripts.validate_rules import _bps, _num, _pct, write  # noqa: E402


def render(report: dict) -> str:
    s = report["sample"]
    lines = [
        f"# Astro signals beyond market controls — NIFTY ({report['generated'][:10]})",
        "",
        f"Sample: {s['first']} → {s['last']}. Horizons: {', '.join(f'{h}d' for h in report['horizons'])}. "
        f"Permutations: {report['n_permutations']} (circular shift of the astro signal). "
        f"Fingerprint version `{report['fingerprint_version']}`.",
        "",
        "Generated by `scripts/validate_incremental.py`; method in `sbc/incremental.py`.",
        "",
        f"Controls (known at the previous close): {', '.join(f'`{c}`' for c in report['controls'])}. "
        "FII/DII flows are not included yet (no free history before 2026-10-01).",
        "",
        "- **beta**: return per unit of signal *after* the controls, in bps. For a ±1 signal, "
        "the gap between bullish and bearish calls is twice this.",
        "- **beta raw**: the same without controls. A large drop means the signal was "
        "echoing market conditions.",
        "- **q**: Benjamini–Hochberg across every test in this report.",
        "",
        "## Do the market controls forecast anything? (yearly walk-forward OLS, 2012 on)",
        "",
        "| horizon | n | hit | base | excess bps | OOS R² |",
        "|---|---|---|---|---|---|",
    ]
    for h, sk in report["controls_skill"].items():
        if sk.get("status") != "ok":
            lines.append(f"| {h}d | – | – | – | – | – |")
            continue
        lines.append(f"| {h}d | {sk['n']} | {_pct(sk['hit_rate'], 1)} | {_pct(sk['baseline'], 1)} | "
                     f"{_bps(sk['excess'])} | {sk['oos_r2']:+.4f} |")

    verdicts = {}
    for r in report["results"]:
        verdicts.setdefault(r["verdict"], []).append(f"{r['rule']} ({r['horizon']}d)")
    lines += ["", "## Summary", ""]
    for v in ("adds information", "nothing beyond the market", "insufficient"):
        items = verdicts.get(v, [])
        lines.append(f"- **{v}** ({len(items)}): {', '.join(items) if items else '—'}")
    lines += ["", "## Partial effect of each astro signal", "",
              "| signal | h | n | beta bps | beta raw bps | p | q | verdict |",
              "|---|---|---|---|---|---|---|---|"]
    for r in sorted(report["results"], key=lambda r: (r["rule"], r["horizon"])):
        if r["status"] != "ok":
            lines.append(f"| {r['rule']} | {r['horizon']} | {r['n']} | – | – | – | – | {r['verdict']} |")
            continue
        lines.append(f"| {r['rule']} | {r['horizon']} | {r['n']} | {_bps(r['beta'])} | {_bps(r['beta_raw'])} | "
                     f"{_num(r['p'])} | {_num(r['q'])} | **{r['verdict']}** |")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--perm", type=int, default=1000)
    args = parser.parse_args()
    t0 = time.perf_counter()
    report = inc.run(n_perm=args.perm)
    write(report, "incremental_validation", render(report))
    print(f"wrote docs/research/incremental_validation_*.md/.json in {time.perf_counter() - t0:.0f}s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
